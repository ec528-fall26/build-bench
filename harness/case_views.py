"""Give each case of a multi-case validator bundle its own rcran-style folder.

The 10-case local bundle (development-v1) has one run.sh for every case,
selected with --case ID, and the cases under cases/<id>/. The harness, Part D
and the Demo 3 script expect one bundle per case: a run.sh that builds that
case and a case/ folder (as buildbench-local-rcran-v1 has). A view is exactly
that, without copying anything:

    <views>/<case-id>/run.sh   runs the bundle's run.sh with --case <case-id>
    <views>/<case-id>/case     symlink to <bundle>/cases/<case-id>

Nothing in the bundle is modified.

Usage (on the ARM64 host):
    python3 -m harness.case_views ~/buildbench-local-development-v1 ~/bb-cases
    python3 -m harness.run_case --bundle ~/bb-cases/<case-id> ...
"""

from __future__ import annotations

import argparse
from pathlib import Path
import shlex
import sys


WRAPPER = """#!/usr/bin/env bash
# Generated by harness/case_views.py: one case of {bundle} as its own bundle.
cd {root} && exec bash ./run.sh --case {case_id} "$@"
"""


def make_views(bundle: Path, views: Path) -> list[Path]:
    """Create (or refresh) one view per case; returns the view folders."""
    bundle, views = Path(bundle).resolve(), Path(views).resolve()
    if not (bundle / "run.sh").is_file() or not (bundle / "cases").is_dir():
        raise ValueError(f"{bundle} has no run.sh and cases/: not a multi-case bundle")
    if views.is_relative_to(bundle):
        raise ValueError("views must be outside the bundle, which stays unmodified")
    made = []
    for case in sorted(p for p in (bundle / "cases").iterdir() if p.is_dir()):
        if not (case / "manifest.json").is_file():
            continue
        view = views / case.name
        view.mkdir(parents=True, exist_ok=True)
        (view / "run.sh").write_text(WRAPPER.format(
            bundle=bundle.name, root=shlex.quote(str(bundle)), case_id=shlex.quote(case.name)))
        link = view / "case"
        if link.is_symlink() or link.exists():
            if not link.is_symlink() or link.resolve() != case.resolve():
                raise ValueError(f"{link} exists and is not a link to {case}")
        else:
            link.symlink_to(case, target_is_directory=True)
        made.append(view)
    return made


def main(argv: list) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("bundle", type=Path, help="extracted multi-case bundle (run.sh, cases/)")
    parser.add_argument("views", type=Path, help="folder to create the per-case views in")
    args = parser.parse_args(argv)
    try:
        made = make_views(args.bundle, args.views)
    except ValueError as error:
        print(error, file=sys.stderr)
        return 1
    for view in made:
        print(view)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
